import { RetrievalResult } from '@supportpilot/shared';
import { buildUntrustedBlock } from './boundary';

export interface HistoryTurn {
  role: 'customer' | 'agent';
  text: string;
}

export interface ToolResultFact {
  tool: string;
  orderId?: string;
  ok: boolean;
  /** 'OK' on success, otherwise a ToolRunErrorCode-shaped string. */
  code: string;
  /** Already-validated structured fields only (e.g. a GetOrderOutput) - still wrapped as untrusted below, since a field like `status` is an unconstrained string from an upstream system, not something our own code generated. */
  fields?: Record<string, unknown>;
}

function buildHistoryBlocks(boundary: string, history: HistoryTurn[]): string[] {
  return history.map((turn) => buildUntrustedBlock('history_turn', `role=${turn.role}\n${turn.text}`, boundary));
}

/** Call 1 (plan) sees only the customer's message and prior history - no policy chunks or tool results exist yet. */
export function buildPlanUserContent(boundary: string, customerMessage: string, history: HistoryTurn[]): string {
  return [...buildHistoryBlocks(boundary, history), buildUntrustedBlock('customer_message', customerMessage, boundary)].join('\n\n');
}

/**
 * Call 2 (compose) additionally sees retrieved policy chunks, tool result
 * facts, and derived facts. Policy chunks and tool results are untrusted
 * (the chunk's own text, and any upstream-supplied string field like
 * `status`/`carrier`, are both external content, never generated by our
 * own code) and go through the same buildUntrustedBlock treatment as the
 * customer message. derivedFacts is the one exception: it is a plain
 * JSON object of ONLY numbers/booleans/strings OUR OWN code computed
 * (daysSinceDelivery, remainingRefundable, etc.) - there is no external
 * text inside it to neutralize, so it is included literally, unwrapped.
 */
export function buildComposeUserContent(
  boundary: string,
  customerMessage: string,
  history: HistoryTurn[],
  policyChunks: RetrievalResult[],
  toolResults: ToolResultFact[],
  derivedFacts: Record<string, unknown>,
): string {
  const parts = [...buildHistoryBlocks(boundary, history), buildUntrustedBlock('customer_message', customerMessage, boundary)];

  for (const chunk of policyChunks) {
    const text = `chunkKey=${chunk.chunkKey}\ntitle=${chunk.documentTitle}\nheading=${chunk.headingPath}\n${chunk.text}`;
    parts.push(buildUntrustedBlock('policy_chunk', text, boundary));
  }

  for (const result of toolResults) {
    const orderIdPart = result.orderId ? ` orderId=${result.orderId}` : '';
    const fieldsPart = result.fields ? ` fields=${JSON.stringify(result.fields)}` : '';
    const text = `tool=${result.tool}${orderIdPart} ok=${result.ok} code=${result.code}${fieldsPart}`;
    parts.push(buildUntrustedBlock('tool_result', text, boundary));
  }

  parts.push(`DERIVED_FACTS (computed by code, not by you): ${JSON.stringify(derivedFacts)}`);

  return parts.join('\n\n');
}
